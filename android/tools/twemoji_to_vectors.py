#!/usr/bin/env python3
"""Generate Android vector drawables for every emoji the iOS app shows.

Android 9 to 12 can't draw the bundled Twemoji COLR colour font (the glyphs render
blank; checked on an API 28 emulator, Oct 2026), so each emoji is drawn from a vector
drawable instead, identical on every Android version. Single-sourced from the iOS app:

  emoji list: Keel/Models/Mood.swift and Keel/Models/MoodPack.swift
  artwork:    Keel/Resources/Fonts/TwemojiMozilla.ttf (Twemoji, CC-BY 4.0, credited in About)

Writes core/designsystem/src/main/res/drawable/twemoji_<codepoint>.xml and
core/designsystem/src/main/kotlin/.../TwemojiVectors.kt. Re-run after changing a mood
pack:  python3 -m pip install fonttools && python3 android/tools/twemoji_to_vectors.py
"""
import pathlib
import re

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

REPO = pathlib.Path(__file__).resolve().parents[2]
DS = REPO / "android/core/designsystem/src/main"
PKG = "com.therecalibrationyears.keel.designsystem"
EMOJI = re.compile("[\U0001F000-\U0001FAFF☀-➿⬀-⯿]")
# The Twemoji art fills a 512-unit square from y = -64 to 448 (font units, y up).
EM, TOP = 512, 448


def emoji_in_ios_sources():
    found = []
    for name in ("Keel/Models/Mood.swift", "Keel/Models/MoodPack.swift"):
        for ch in EMOJI.findall((REPO / name).read_text()):
            if ch not in found:
                found.append(ch)
    return found


def fmt(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def vector_xml(font, glyph):
    glyphs = font.getGlyphSet()
    palette = font["CPAL"].palettes[0]
    paths = []
    for layer in font["COLR"].ColorLayers[glyph]:
        pen = SVGPathPen(glyphs, ntos=fmt)
        glyphs[layer.name].draw(TransformPen(pen, (1, 0, 0, -1, 0, TOP)))  # flip y
        c = palette[layer.colorID]
        colour = f"#{c.alpha:02X}{c.red:02X}{c.green:02X}{c.blue:02X}"
        paths.append(f'    <path android:fillColor="{colour}" android:pathData="{pen.getCommands()}" />')
    return (
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
        "<!-- Generated by android/tools/twemoji_to_vectors.py from TwemojiMozilla.ttf. Do not edit. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="24dp" android:height="24dp"\n'
        f'    android:viewportWidth="{EM}" android:viewportHeight="{EM}">\n'
        + "\n".join(paths) + "\n</vector>\n"
    )


def main():
    font = TTFont(REPO / "Keel/Resources/Fonts/TwemojiMozilla.ttf")
    cmap = font.getBestCmap()
    drawable_dir = DS / "res/drawable"
    drawable_dir.mkdir(parents=True, exist_ok=True)
    for old in drawable_dir.glob("twemoji_*.xml"):
        old.unlink()
    entries = []
    for ch in emoji_in_ios_sources():
        name = f"twemoji_{ord(ch):x}"
        (drawable_dir / f"{name}.xml").write_text(vector_xml(font, cmap[ord(ch)]))
        entries.append(f'    "{ch}" to R.drawable.{name},')
    kt = DS / "kotlin" / PKG.replace(".", "/") / "TwemojiVectors.kt"
    kt.write_text(
        f"package {PKG}\n\n"
        "// Generated by android/tools/twemoji_to_vectors.py. Do not edit.\n\n"
        "/** Every emoji the app shows (the mood packs), keyed by glyph without variation selectors. */\n"
        "internal val twemojiVectors: Map<String, Int> = mapOf(\n" + "\n".join(entries) + "\n)\n"
    )
    print(f"{len(entries)} emoji -> {drawable_dir.relative_to(REPO)}")


if __name__ == "__main__":
    main()
